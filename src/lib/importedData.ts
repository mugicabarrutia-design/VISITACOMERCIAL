// Helper para generar visitas asociadas a los nuevos clientes
const makeDate = (daysOffset: number, startHour: number, startMinute: number, durationHours: number) => {
  const d = new Date();
  d.setDate(d.getDate() + daysOffset);
  d.setHours(startHour, startMinute, 0, 0);
  const start = new Date(d);
  const end = new Date(d);
  end.setMinutes(end.getMinutes() + Math.round(durationHours * 60));
  return {
    inicio: start.toISOString(),
    fin: end.toISOString(),
  };
};

